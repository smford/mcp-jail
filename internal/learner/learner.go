package learner

import (
	"fmt"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"

	"gopkg.in/yaml.v3"
	"github.com/smford/mcp-jail/internal/config"
)

// Learner records tool invocations during an active MCP session and synthesizes a least-privilege security policy.
type Learner struct {
	mu          sync.Mutex
	tools       map[string]int
	paths       map[string]int
	commands    []string
	totalCalls  int
	totalTokens int64
}

// NewLearner constructs a new policy Learner.
func NewLearner() *Learner {
	return &Learner{
		tools: make(map[string]int),
		paths: make(map[string]int),
	}
}

// RecordToolCall records an observed tool name and its arguments.
func (l *Learner) RecordToolCall(name string, args map[string]interface{}) {
	l.mu.Lock()
	defer l.mu.Unlock()

	l.totalCalls++
	l.tools[name]++

	// Extract paths and commands from arguments
	for k, v := range args {
		kLower := strings.ToLower(k)
		if str, ok := v.(string); ok && str != "" {
			if strings.Contains(kLower, "path") || strings.Contains(kLower, "file") || strings.Contains(kLower, "dir") {
				cleanPath := filepath.Clean(str)
				l.paths[cleanPath]++
			}
			if strings.Contains(kLower, "cmd") || strings.Contains(kLower, "command") {
				l.commands = append(l.commands, str)
			}
		}
	}
}

// AddTokens increments the observed token consumption.
func (l *Learner) AddTokens(tokens int64) {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.totalTokens += tokens
}

// GenerateConfig produces a minimal least-privilege Config based on observed activity.
func (l *Learner) GenerateConfig() *config.Config {
	l.mu.Lock()
	defer l.mu.Unlock()

	cfg := config.DefaultConfig()

	// 1. Tool allowlist
	var allowedTools []string
	for tool := range l.tools {
		escaped := fmt.Sprintf("^%s$", regexp.QuoteMeta(tool))
		allowedTools = append(allowedTools, escaped)
	}
	sort.Strings(allowedTools)
	cfg.Tools.Allowed = allowedTools

	// 2. Allowed filesystem roots
	roots := map[string]bool{"." : true}
	for p := range l.paths {
		if filepath.IsAbs(p) {
			// Find directory root
			roots[filepath.Dir(p)] = true
		}
	}
	var allowedRoots []string
	for r := range roots {
		allowedRoots = append(allowedRoots, r)
	}
	sort.Strings(allowedRoots)
	cfg.Filesystem.AllowedRoots = allowedRoots

	// 3. Sensible limits
	callsPerMin := l.totalCalls * 2
	if callsPerMin < 30 {
		callsPerMin = 30
	}
	totalCalls := l.totalCalls * 2
	if totalCalls < 50 {
		totalCalls = 50
	}
	tokensLimit := l.totalTokens * 2
	if tokensLimit < 100000 {
		tokensLimit = 100000
	}

	cfg.Limits.MaxToolCallsPerMinute = callsPerMin
	cfg.Limits.MaxTotalCallsPerSession = totalCalls
	cfg.Limits.MaxSessionTokens = tokensLimit

	return cfg
}

// GenerateYAML converts the learned configuration into commented YAML.
func (l *Learner) GenerateYAML() (string, error) {
	cfg := l.GenerateConfig()
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return "", err
	}

	header := fmt.Sprintf(`# .mcp-jail.learned.yaml
# Automatically generated by 'mcp-jail learn'
# Observed activity: %d tool calls, %d unique tools, %d estimated tokens
# Review and adjust before replacing your production policy.

`, l.totalCalls, len(l.tools), l.totalTokens)

	return header + string(data), nil
}
